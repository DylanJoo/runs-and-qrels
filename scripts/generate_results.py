#!/usr/bin/env python3
"""
Generate RESULTS.md from evaluation JSON files.

This script scans the results/ directory for JSON files and generates
a markdown file with all evaluation results.

Usage:
    python scripts/generate_results.py
"""

import json
from pathlib import Path


def main():
    results_dir = Path("results")
    output_file = Path("RESULTS.md")
    
    # Collect all JSON result files
    result_files = sorted(results_dir.glob("*.json"))
    
    lines = []
    lines.append("# Evaluation Results")
    lines.append("")
    lines.append("This file is automatically generated by the evaluation pipeline.")
    lines.append("")
    
    if not result_files:
        lines.append("No evaluation results found.")
    else:
        for result_file in result_files:
            run_name = result_file.stem.replace("_results", "")
            lines.append(f"## {run_name}")
            lines.append("")
            
            try:
                with open(result_file, 'r') as f:
                    results = json.load(f)
                
                lines.append("| Metric | Score |")
                lines.append("|--------|-------|")
                for metric, score in results.items():
                    lines.append(f"| {metric} | {score:.4f} |")
                lines.append("")
            except json.JSONDecodeError as e:
                lines.append(f"Error: Invalid JSON format in {result_file}: {e}")
                lines.append("")
            except FileNotFoundError:
                lines.append(f"Error: Result file not found: {result_file}")
                lines.append("")
    
    # Write the markdown file
    with open(output_file, 'w') as f:
        f.write("\n".join(lines))
    
    print(f"Generated {output_file}")


if __name__ == '__main__':
    main()
